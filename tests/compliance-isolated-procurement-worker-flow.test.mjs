import test from "node:test";
import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {IsolatedProcurementWorker,executeSyntheticPurchase} from "../src/lib/compliance/isolated-procurement-worker.ts";
import {checkInternalAgentEventRequest} from "../src/lib/compliance/internal-agent-event-service.ts";
import {signProcurementBatch} from "../src/lib/compliance/signed-agent-event-channel.ts";
const validRole={roleName:"compliance_agent_replay_rls_probe",canLogin:false,bypassRls:false,superuser:false,canCreateRole:false,canCreateDb:false,rlsEnabled:true,rlsForced:true};
const setup=(variant)=>{
 const now=Date.now(),secret=randomBytes(32);
 const scope={tenantId:"tenant-demo-a",organizationId:"organization-demo-a",agentKey:"AG-PRC-001"};
 const events=executeSyntheticPurchase("RUN-"+variant.replace(/[^A-Za-z0-9_-]/g,"-"),variant);
 const envelope=signProcurementBatch({
  version:"1",...scope,issuedAt:now,nonce:randomBytes(24).toString("base64url"),
  payload:JSON.stringify({schemaVersion:"1",agentKey:"AG-PRC-001",events})
 },secret);
 const record={...scope,keyId:"worker-demo-key",status:"active",validFrom:now-1000,validUntil:now+60000,secret};
 const seen=new Set();
 const replayExecutor={insertOnce:async(_sql,parts)=>{
  const key=parts.slice(0,4).join(":");
  if(seen.has(key))return {rows:[]};
  seen.add(key);return {rows:[{nonce:parts[3]}]};
 }};
 return {events,request:{keyId:record.keyId,envelope},lookup:{resolve:async()=>record},
  replayExecutor,databaseRoleFacts:async()=>validRole,verifiedExpectedScope:scope,now};
};
test("executed normal process generates signed events; Guardian requires review",async()=>{
 const data=setup("normal");
 const result=await checkInternalAgentEventRequest(data);
 assert.equal(data.events.length,7);
 assert.equal(result.localReview.audit.orderObserved,true);
 assert.equal(result.localReview.audit.status,"review-required");
 assert.deepEqual(result.localReview.audit.findings.map(f=>f.code),["UNVERIFIED_SOURCE"]);
 assert.equal(result.transportedByAuthenticatedAgent,true);
 assert.equal(result.verifiedBusinessEvidence,false);
});
test("Guardian spots actual early-order attempt generated by worker",async()=>{
 const data=setup("early-order");
 const findings=(await checkInternalAgentEventRequest(data)).localReview.audit.findings;
 assert.ok(findings.some(f=>f.code==="ORDER_BEFORE_APPROVAL"&&f.haltRecommended));
});
test("Guardian spots missing human approval",async()=>{
 const data=setup("missing-approval");
 const findings=(await checkInternalAgentEventRequest(data)).localReview.audit.findings;
 assert.ok(findings.some(f=>f.code==="MISSING_HUMAN_APPROVAL"&&f.haltRecommended));
});
test("Guardian spots missing evidence reference",async()=>{
 const data=setup("missing-evidence");
 const findings=(await checkInternalAgentEventRequest(data)).localReview.audit.findings;
 assert.ok(findings.some(f=>f.code==="MISSING_EVIDENCE"));
});
test("worker cannot impersonate human approval",()=>{
 const w=new IsolatedProcurementWorker("RUN-001");
 assert.throws(()=>w.execute({kind:"human-approved",actorId:"AG-PRC-001",evidenceRef:"synthetic-approval"}));
});
test("worker does not permit arbitrary real-world payloads",()=>{
 const w=new IsolatedProcurementWorker("RUN-002");
 assert.throws(()=>w.execute({kind:"request-created",actorId:"requester-demo",evidenceRef:"real customer name"}));
});
test("signed worker output cannot be replayed",async()=>{
 const data=setup("normal");
 await checkInternalAgentEventRequest(data);
 await assert.rejects(checkInternalAgentEventRequest(data),/replay/i);
});
test("database role bypass blocks worker events before nonce write",async()=>{
 const data=setup("normal");let wrote=false;
 data.databaseRoleFacts=async()=>({...validRole,bypassRls:true});
 data.replayExecutor={insertOnce:async()=>{wrote=true;return {rows:[]}}};
 await assert.rejects(checkInternalAgentEventRequest(data));
 assert.equal(wrote,false);
});
